"""Place named types in owning modules and plan explicit cross-module imports."""
from __future__ import annotations

import posixpath
from collections import defaultdict
from typing import Any

from .types import Types, js, symbol


JSON_PATH = "frontend/src/runtime/contracts.ts"


def relative(source: str, target: str) -> str:
    value = posixpath.splitext(posixpath.relpath(target, posixpath.dirname(source)))[0]
    return value if value.startswith(".") else "./" + value


def named_ids(value: Any) -> set[str]:
    if isinstance(value, list):
        return {key for item in value for key in named_ids(item)}
    if not isinstance(value, dict):
        return set()
    result = {value["type_id"]} if value.get("kind") == "named" else set()
    return result | {key for item in value.values() for key in named_ids(item)}


def uses_json(value: Any) -> bool:
    if isinstance(value, list):
        return any(uses_json(item) for item in value)
    if not isinstance(value, dict):
        return False
    return value.get("kind") == "scalar" and value.get("name") == "json" or any(uses_json(item) for item in value.values())


class ModuleContracts:
    def __init__(self, types: Types, consumers: list[tuple[int, str, Any]], fallback: str) -> None:
        self.types = types
        self.imports: dict[str, dict[tuple[bool, str], set[str]]] = defaultdict(lambda: defaultdict(set))
        self.declarations: dict[str, list[str]] = defaultdict(list)
        self.references: dict[str, dict[str, dict[str, str]]] = defaultdict(dict)
        self.owners = {}
        for priority, path, values in sorted(consumers, key=lambda row: (row[0], row[1])):
            pending, seen = list(named_ids(values)), set()
            while pending:
                key = pending.pop()
                if key in seen:
                    continue
                if key not in types.definitions:
                    raise ValueError(f"Unknown frontend named type: {key}")
                seen.add(key)
                self.owners.setdefault(key, path)
                pending.extend(named_ids(types.definitions[key]) - seen)
        for key in types.definitions:
            self.owners.setdefault(key, fallback)
        for key, definition in sorted(types.definitions.items()):
            path = self.owners[key]
            self.use_values(path, definition)
            name = symbol("Type", key)
            value = types.fields(definition["fields"], semantic=False) if definition["kind"] == "object" else " | ".join(js(item) for item in definition["values"]) or "never"
            self.declarations[path].append(f"export type {name} = {value};")
            self.references[path]["FRONTEND::TYPE::" + key] = self.named_reference(key)

    def named_reference(self, key: str) -> dict[str, str]:
        return {"type_id": "FRONTEND::TYPE::" + key, "file": self.owners[key], "symbol": symbol("Type", key)}

    def add_import(self, path: str, name: str, target: str, *, type_only: bool = False) -> None:
        if path != target:
            self.imports[path][type_only, relative(path, target)].add(name)

    def use_values(self, path: str, values: Any) -> None:
        for key in named_ids(values):
            reference = self.named_reference(key)
            self.references[path][reference["type_id"]] = reference
            self.add_import(path, reference["symbol"], reference["file"], type_only=True)
        if uses_json(values):
            self.add_import(path, "JSONValue", JSON_PATH, type_only=True)

    def fields(self, path: str, name: str, fields: list[dict[str, Any]], identity: str) -> dict[str, str]:
        self.use_values(path, fields)
        self.declarations[path].append(f"export type {name} = {self.types.fields(fields, semantic=False)};")
        return self.reference(path, name, identity)

    @staticmethod
    def reference(path: str, name: str, identity: str) -> dict[str, str]:
        return {"type_id": "FRONTEND::" + identity, "file": path, "symbol": name}

    def render(self, path: str, body: list[str]) -> str:
        lines = ["// Generated by ARC. Implement the marked bodies from the Frontend IR."]
        for (type_only, specifier), names in sorted(self.imports[path].items()):
            lines.append(f'import {"type " if type_only else ""}{{ {", ".join(sorted(names))} }} from {js(specifier)};')
        return "\n".join([*lines, "", *self.declarations[path], "", *body, ""])
