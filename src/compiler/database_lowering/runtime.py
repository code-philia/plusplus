"""TypeScript connection and explicit table initialization templates."""
from __future__ import annotations

import json


def render_runtime_sources(statements: list[str]) -> dict[str, str]:
    initialize = '''// Generated by ARC. Importing this module does not open a database.
import type Database from "better-sqlite3";

export const schemaInitializationStatements = STATEMENTS as const;

export function initializeDatabase(connection: Database.Database): void {
  connection.pragma("foreign_keys = ON");
  connection.transaction(() => {
    for (const statement of schemaInitializationStatements) connection.exec(statement);
  })();
}
'''.replace('STATEMENTS', json.dumps(statements, ensure_ascii=False, indent=2))
    client = '''// Generated by ARC. Connections have an explicit owner and lifetime.
import Database from "better-sqlite3";
import { drizzle } from "drizzle-orm/better-sqlite3";
import { mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import * as schema from "./schema.js";

const defaultDatabase = fileURLToPath(new URL("../../data/app.db", import.meta.url));
export function createDatabaseClient(url = process.env.DATABASE_URL ?? defaultDatabase) {
  const path = url.trim();
  if (!path) throw new Error("DATABASE_URL must not be empty.");
  if (path !== ":memory:") mkdirSync(dirname(resolve(path)), { recursive: true });
  const connection = new Database(path);
  try {
    connection.pragma("foreign_keys = ON");
    return { database: drizzle(connection, { schema }), connection, close: () => connection.close() };
  } catch (error) {
    connection.close();
    throw error;
  }
}
export type DatabaseClient = ReturnType<typeof createDatabaseClient>;

// Repository bindings are assigned by the composition root, never on import.
export let database: DatabaseClient["database"];
export let sqliteDatabase: Database.Database;
export function bindDatabaseClient(client: DatabaseClient): void {
  database = client.database;
  sqliteDatabase = client.connection;
}
'''
    init = '''// Generated by ARC. Initializes tables without resetting or seeding data.
import { createDatabaseClient } from "./client.js";
import { initializeDatabase } from "./initialize.js";
const client = createDatabaseClient();
try { initializeDatabase(client.connection); } finally { client.close(); }
'''
    return {
        'backend/src/db/client.ts': client,
        'backend/src/db/initialize.ts': initialize,
        'backend/src/db/init.ts': init,
    }
