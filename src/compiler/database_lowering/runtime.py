"""TypeScript connection and explicit table initialization templates."""
from __future__ import annotations

import json
import hashlib


def render_runtime_sources(statements: list[str]) -> dict[str, str]:
    initialize = '''// Generated by ARC. Importing this module does not open a database.
import type Database from "better-sqlite3";
import { createHash } from "node:crypto";
import { registerDomainFunctions } from "./domain-rules.js";

export const schemaInitializationStatements = STATEMENTS as const;
const schemaFingerprint = FINGERPRINT;
function catalog(connection: Database.Database): string {
  const rows = connection.prepare("SELECT type, name, tbl_name, sql FROM sqlite_master WHERE substr(name, 1, 7) <> 'sqlite_' AND name <> 'arc_schema_identity' ORDER BY type, name").all();
  return createHash("sha256").update(JSON.stringify(rows)).digest("hex");
}

export function initializeDatabase(connection: Database.Database): void {
  registerDomainFunctions(connection);
  connection.pragma("foreign_keys = ON");
  connection.transaction(() => {
    const marker = connection.prepare("SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = 'arc_schema_identity'").get();
    if (marker) {
      const stored = connection.prepare("SELECT fingerprint, catalog_hash FROM arc_schema_identity WHERE id = 1").get() as { fingerprint: string; catalog_hash: string } | undefined;
      if (!stored || stored.fingerprint !== schemaFingerprint || stored.catalog_hash !== catalog(connection)) {
        throw new Error("SCHEMA_INITIALIZATION_MISMATCH: migrations and changed existing schemas are unsupported.");
      }
      return;
    }
    const existing = connection.prepare("SELECT 1 FROM sqlite_master WHERE substr(name, 1, 7) <> 'sqlite_' LIMIT 1").get();
    if (existing) throw new Error("SCHEMA_INITIALIZATION_REQUIRES_EMPTY_DATABASE: use a fresh SQLite database.");
    for (const statement of schemaInitializationStatements) connection.exec(statement);
    connection.exec("CREATE TABLE arc_schema_identity (id INTEGER PRIMARY KEY CHECK (id = 1), fingerprint TEXT NOT NULL, catalog_hash TEXT NOT NULL)");
    connection.prepare("INSERT INTO arc_schema_identity (id, fingerprint, catalog_hash) VALUES (1, ?, ?)").run(schemaFingerprint, catalog(connection));
  })();
}
'''.replace('STATEMENTS', json.dumps(statements, ensure_ascii=False, indent=2)).replace(
        'FINGERPRINT', json.dumps(hashlib.sha256(json.dumps(statements, ensure_ascii=False).encode()).hexdigest()))
    client = '''// Generated by ARC. Connections have an explicit owner and lifetime.
import Database from "better-sqlite3";
import { drizzle } from "drizzle-orm/better-sqlite3";
import { mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import * as schema from "./schema.js";
import { registerDomainFunctions } from "./domain-rules.js";

const defaultDatabase = fileURLToPath(new URL("../../data/app.db", import.meta.url));
export function createDatabaseClient(url = process.env.DATABASE_URL ?? defaultDatabase) {
  const path = url.trim();
  if (!path) throw new Error("DATABASE_URL must not be empty.");
  if (path !== ":memory:") mkdirSync(dirname(resolve(path)), { recursive: true });
  const connection = new Database(path);
  try {
    connection.pragma("foreign_keys = ON");
    registerDomainFunctions(connection);
    const database = drizzle(connection, { schema });
    return { database, connection, close: () => connection.close() };
  } catch (error) {
    connection.close();
    throw error;
  }
}
export type DatabaseClient = ReturnType<typeof createDatabaseClient>;

// Repository bindings are assigned by the composition root, never on import.
export let database: DatabaseClient["database"];
export let sqliteDatabase: Database.Database;
export function bindDatabaseClient(client: DatabaseClient): void {
  database = client.database;
  sqliteDatabase = client.connection;
}

/** Use for an atomic sequence of repository calls sharing the bound connection. */
export function schemaTransaction<T>(work: () => T): T {
  return sqliteDatabase.transaction(() => {
    const result = work();
    if (result instanceof Promise) throw new Error("SQLite transaction callbacks must be synchronous.");
    return result;
  })();
}
'''
    init = '''// Generated by ARC. Initializes tables without resetting or seeding data.
import { createDatabaseClient } from "./client.js";
import { initializeDatabase } from "./initialize.js";
const client = createDatabaseClient();
try { initializeDatabase(client.connection); } finally { client.close(); }
'''
    return {
        'backend/src/db/client.ts': client,
        'backend/src/db/initialize.ts': initialize,
        'backend/src/db/init.ts': init,
    }
