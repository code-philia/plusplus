"""Compiler-owned connection and schema-only initialization source templates."""
from __future__ import annotations

import json
from typing import Any


def render_runtime_sources(statements: list[str], tables: list[dict[str, Any]]) -> dict[str, str]:
    table_names = sorted(item['name'] for item in tables)
    schema_module = f'''// Generated by ARC. No connection or data changes at import time.
export const schemaInitializationStatements = {json.dumps(statements, ensure_ascii=False, indent=2)};
const tableNames = {json.dumps(table_names)};

export function initializeSchema(database) {{
  database.pragma("foreign_keys = ON");
  const initialize = database.transaction(() => {{
    for (const statement of schemaInitializationStatements) database.exec(statement);
  }});
  initialize();
}}

// Schema-only baseline for isolated test databases; contains no fixtures.
export function resetToBaseline(database) {{
  initializeSchema(database);
  database.pragma("foreign_keys = OFF");
  try {{
    const reset = database.transaction(() => {{
      for (const name of tableNames) database.exec('DELETE FROM "' + name + '"');
    }});
    reset();
  }} finally {{
    database.pragma("foreign_keys = ON");
  }}
}}
'''
    client = '''// Generated by ARC database lowering. Do not edit.
import Database from "better-sqlite3";
import { drizzle } from "drizzle-orm/better-sqlite3";
import { mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import * as schema from "./schema/index.js";
import { initializeSchema, resetToBaseline } from "../../database-schema.mjs";

const defaultDatabase = fileURLToPath(new URL("../../data/app.db", import.meta.url));
const databaseUrl = (process.env.DATABASE_URL ?? defaultDatabase).trim();
if (!databaseUrl) throw new Error("DATABASE_URL must not be empty.");
if (databaseUrl !== ":memory:") mkdirSync(dirname(resolve(databaseUrl)), { recursive: true });
export const sqliteDatabase = new Database(databaseUrl);
try {
  initializeSchema(sqliteDatabase);
} catch (error) {
  sqliteDatabase.close();
  throw error;
}
export const database = drizzle(sqliteDatabase, { schema });
export function resetDatabase(): void { resetToBaseline(sqliteDatabase); }
'''
    initializer = '''// Generated by ARC. Creates tables only; never resets or seeds data.
import Database from "better-sqlite3";
import { mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { initializeSchema } from "./database-schema.mjs";
const defaultDatabase = fileURLToPath(new URL("./data/app.db", import.meta.url));
const databaseUrl = (process.env.DATABASE_URL ?? defaultDatabase).trim();
if (!databaseUrl) throw new Error("DATABASE_URL must not be empty.");
if (databaseUrl !== ":memory:") mkdirSync(dirname(resolve(databaseUrl)), { recursive: true });
const connection = new Database(databaseUrl);
try { initializeSchema(connection); } finally { connection.close(); }
'''
    return {
        'backend/src/db/client.ts': client,
        'backend/database-schema.mjs': schema_module,
        'backend/database-schema.d.mts': '''import type Database from "better-sqlite3";
export declare const schemaInitializationStatements: readonly string[];
export declare function initializeSchema(database: Database.Database): void;
export declare function resetToBaseline(database: Database.Database): void;
''',
        # Existing test harnesses keep their schema-only reset entry point.
        'backend/database-baseline.mjs': 'export { resetToBaseline } from "./database-schema.mjs";\n',
        'backend/database-baseline.d.mts': 'export { resetToBaseline } from "./database-schema.mjs";\n',
        'backend/init-db.mjs': initializer,
    }
