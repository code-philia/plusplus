"""SQLite storage, constraints, DDL and runtime bindings for neutral Schema IR."""
from __future__ import annotations

import json
from typing import Any

from .runtime import render_runtime_sources
from .sql import constraint_sql, identifier, literal
from .strategy import StrategyResult


SQLITE_TYPES = {
    'string': 'TEXT', 'uuid': 'TEXT', 'date': 'TEXT', 'datetime': 'TEXT',
    'json': 'TEXT', 'integer': 'INTEGER', 'number': 'REAL', 'boolean': 'INTEGER',
}


def storage_type(column: dict[str, Any]) -> str:
    try:
        return SQLITE_TYPES[column['type']]
    except KeyError:
        raise ValueError(f'Unsupported SQLite logical type: {column.get("type")!r}') from None


def storage_checks(column: dict[str, Any]) -> list[str]:
    name, kind = identifier(column['name']), column['type']
    if kind == 'boolean':
        return [f'{name} IN (0, 1)']
    if kind == 'json':
        return [f'json_valid({name})']
    if kind == 'integer':
        return [f'typeof({name}) = \'integer\'']
    if kind == 'number':
        return [f'typeof({name}) IN (\'integer\', \'real\')']
    return [f'typeof({name}) = \'text\'']


def render_statements(schema: dict[str, Any]) -> list[str]:
    statements = []
    for table in sorted(schema['tables'], key=lambda item: item['name']):
        definitions = []
        for column in sorted(table['columns'], key=lambda item: item['name']):
            qname = identifier(column['name'])
            definition = f'{qname} {storage_type(column)}'
            if not column['nullable']:
                definition += ' NOT NULL'
            default = column['default']
            if default is not None:
                value = default['value']
                if default['kind'] == 'json_literal':
                    value = json.dumps(value, ensure_ascii=False, separators=(',', ':'))
                definition += f' DEFAULT ({literal(value)})'
            for expression in storage_checks(column):
                definition += f' CHECK ({qname} IS NULL OR ({expression}))'
            definitions.append(definition)
        definitions.extend(constraint_sql(item) for item in sorted(table['constraints'], key=lambda item: item['name']))
        statements.append(f'CREATE TABLE IF NOT EXISTS {identifier(table["name"])} (\n  ' + ',\n  '.join(definitions) + '\n);')
    return statements


def render_ddl(schema: dict[str, Any]) -> str:
    return ('-- Generated by ARC SQLite lowering. Creates tables only.\n'
            'PRAGMA foreign_keys = ON;\nBEGIN;\n\n'
            + '\n\n'.join(render_statements(schema)) + '\n\nCOMMIT;\n')


class SQLiteLoweringStrategy:
    dialect = 'sqlite'

    def lower(self, schema: dict[str, Any], symbols: dict[str, Any], files: dict[str, Any]) -> StrategyResult:
        # SQLite signed integer bounds are a strategy decision, not an IR rule.
        for table in schema['tables']:
            for column in table['columns']:
                if column['type'] == 'integer':
                    values = [column.get('properties', {}).get(key) for key in ('minimum', 'maximum')]
                    if column['default'] is not None:
                        values.append(column['default']['value'])
                    if any(value is not None and not -(2**63) <= value <= 2**63 - 1 for value in values):
                        raise ValueError(f'SQLite integer range exceeded: {table["name"]}.{column["name"]}')
        # The column limit includes internal rowid bookkeeping conservatively.
        if any(len(table['columns']) > 1999 for table in schema['tables']):
            raise ValueError('SQLite strategy supports at most 1999 columns per table')
        from .orm import render_bindings
        bindings, tables = render_bindings(schema, symbols, files, storage_type=storage_type, storage_checks=storage_checks)
        statements = render_statements(schema)
        sources = {**bindings, **render_runtime_sources(statements),
                   'backend/sql/schema.sqlite.sql': render_ddl(schema)}
        warnings = []
        if any(column['type'] == 'integer' for table in schema['tables'] for column in table['columns']):
            warnings.append('SQLITE_NUMBER_PRECISION: SQLite stores signed 64-bit integers; the current Drizzle number binding requires JavaScript safe integers.')
        return StrategyResult(sources, tables, statements, {
            'types': SQLITE_TYPES, 'foreign_keys': 'ON', 'text_comparison': 'BINARY',
            'datetime': 'ISO 8601 text; application normalizes to UTC',
            'uuid_generation': 'application', 'initialization': 'create_if_not_exists',
            'schema_migration': 'not supported; existing tables are not altered',
        }, warnings)
