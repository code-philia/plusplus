"""Project-specific SQLite Drizzle bindings derived from relational tables."""
from __future__ import annotations

import json
import posixpath
from typing import Any, Callable

from .sql import constraint_sql


def render_bindings(
    schema: dict[str, Any], symbols: dict[str, Any], files: dict[str, Any], *,
    storage_type: Callable[[dict[str, Any]], str],
    storage_checks: Callable[[dict[str, Any]], list[str]],
) -> tuple[dict[str, str], list[dict[str, Any]]]:
    by_id = {item['id']: item for item in symbols['symbols']}
    locations = {item['symbol_id']: item['path'] for item in files['symbol_locations']}
    sources, rows = {}, []
    table_info = {
        table['name']: (by_id[f'ENTITY_TABLE.{table["name"]}']['symbol'], locations[f'ENTITY_TABLE.{table["name"]}'])
        for table in schema['tables']
    }
    for table in sorted(schema['tables'], key=lambda item: item['name']):
        name = table['name']
        variable, path = table_info[name]
        record = by_id[f'ENTITY.{name}']['symbol']
        imports = [
            {'symbol': item, 'specifier': 'drizzle-orm/sqlite-core', 'import_style': 'named', 'type_only': item == 'AnySQLiteColumn'}
            for item in ['sqliteTable', 'text', 'integer', 'real', 'primaryKey', 'unique', 'foreignKey', 'check', 'AnySQLiteColumn']
        ] + [{'symbol': 'sql', 'specifier': 'drizzle-orm', 'import_style': 'named', 'type_only': False}]
        lines = ['// Generated by ARC from relational Schema IR. Do not edit.',
                 'import { sqliteTable, text, integer, real, primaryKey, unique, foreignKey, check, type AnySQLiteColumn } from "drizzle-orm/sqlite-core";',
                 'import { sql } from "drizzle-orm";']
        for target in sorted({item['referenced_table'] for item in table['constraints'] if item['kind'] == 'FOREIGN_KEY'} - {name}):
            target_variable, target_path = table_info[target]
            relative = posixpath.relpath(target_path, posixpath.dirname(path)).removesuffix('.ts') + '.js'
            if not relative.startswith('.'):
                relative = './' + relative
            lines.append(f'import {{ {target_variable} }} from {json.dumps(relative)};')
            imports.append({'symbol': target_variable, 'specifier': relative, 'from': target_path, 'import_style': 'named', 'type_only': False})
        # Explicit record declarations preserve the existing backend contract.
        lines += ['', f'export interface {record} {{']
        for column in table['columns']:
            kind = storage_type(column)
            ts_type = 'boolean' if column['type'] == 'boolean' else 'number' if kind in {'INTEGER', 'REAL'} else 'string'
            if column['type'] == 'json':
                ts_type = 'JsonValue'
            elif column.get('properties', {}).get('enum'):
                ts_type = ' | '.join(json.dumps(value, ensure_ascii=False) for value in column['properties']['enum'])
            nullable = ' | null' if column['nullable'] else ''
            lines.append(f'  {json.dumps(column["name"])}: {ts_type}{nullable};')
        lines += ['}', '', f'export const {variable} = sqliteTable({json.dumps(name)}, {{']
        uses_json = any(column['type'] == 'json' for column in table['columns'])
        if uses_json:
            lines.insert(3, 'import type { JsonValue } from "@arc/shared";')
            imports.append({'symbol': 'JsonValue', 'specifier': '@arc/shared', 'from': 'shared/src/index.ts', 'import_style': 'named', 'type_only': True})
        for column in table['columns']:
            qname = json.dumps(column['name'])
            kind = storage_type(column)
            if column['type'] == 'json':
                builder = f'text({qname}, {{ mode: "json" }}).$type<JsonValue>()'
            elif column['type'] == 'boolean':
                builder = f'integer({qname}, {{ mode: "boolean" }})'
            else:
                builder = f'{ {"TEXT": "text", "INTEGER": "integer", "REAL": "real"}[kind]}({qname})'
            if column.get('properties', {}).get('enum'):
                union = ' | '.join(json.dumps(value, ensure_ascii=False) for value in column['properties']['enum'])
                builder += f'.$type<{union}>()'
            if not column['nullable']:
                builder += '.notNull()'
            if column['default'] is not None:
                builder += '.default(' + json.dumps(column['default']['value'], ensure_ascii=False) + ')'
            lines.append(f'  {qname}: {builder},')
        lines += ['}, (table) => [']
        lowered_checks = []
        for constraint in table['constraints']:
            columns = ', '.join(f'table[{json.dumps(value)}]' for value in constraint['columns'])
            cname = json.dumps(constraint['name'])
            kind = constraint['kind']
            if kind == 'PRIMARY_KEY':
                entry = f'primaryKey({{ columns: [{columns}] }})'
            elif kind == 'UNIQUE':
                entry = f'unique({cname}).on({columns})'
            elif kind == 'FOREIGN_KEY':
                target = table_info[constraint['referenced_table']][0]
                target_columns = ', '.join(f'{target}[{json.dumps(value)}]' for value in constraint['referenced_columns'])
                # Explicit column annotations prevent TS recursive inference for self/cyclic relationships.
                entry = f'foreignKey((): {{ name: string; columns: [AnySQLiteColumn]; foreignColumns: [AnySQLiteColumn] }} => ({{ name: {cname}, columns: [{columns}], foreignColumns: [{target_columns}] }})).onDelete("restrict").onUpdate("restrict")'
                if len(constraint['columns']) != 1:
                    arity = len(constraint['columns'])
                    tuple_type = '[' + ', '.join(['AnySQLiteColumn'] * arity) + ']'
                    entry = entry.replace('[AnySQLiteColumn]', tuple_type)
            else:
                expression = constraint_sql(constraint).split('CHECK (', 1)[1][:-1]
                entry = f'check({cname}, sql.raw({json.dumps(expression, ensure_ascii=False)}))'
                lowered_checks.append(constraint['name'])
            lines.append(f'  {entry},')
        for column in table['columns']:
            for index, expression in enumerate(storage_checks(column)):
                nullable_expression = f'"{column["name"]}" IS NULL OR ({expression})'
                check_name = f'{name}_{column["name"]}_storage_{index}'
                lines.append(f'  check({json.dumps(check_name)}, sql.raw({json.dumps(nullable_expression)})),')
        lines += [']);', '']
        sources[path] = '\n'.join(lines)
        rows.append({'entity': name, 'table': name, 'table_symbol': variable, 'record_symbol': record, 'path': path, 'lowered_checks': lowered_checks, 'imports': imports})
    barrel = 'backend/src/db/schema/index.ts'
    exports = []
    for row in rows:
        relative = './' + posixpath.relpath(row['path'], posixpath.dirname(barrel)).removesuffix('.ts') + '.js'
        exports.append(f'export * from {json.dumps(relative)};')
    sources[barrel] = '\n'.join(exports or ['export {};']) + '\n'
    return sources, rows
