from __future__ import annotations

import copy
import json
import posixpath
import re
from dataclasses import dataclass, field
from typing import Any


TYPE_MANIFEST_SCHEMA_VERSION = 1
TYPES_GENERATED = "TYPES_GENERATED"

DESIGN_TYPE_MAP = {
    "string": "string",
    "integer": "number",
    "number": "number",
    "boolean": "boolean",
    "date": "string",
    "datetime": "string",
    "uuid": "string",
    "json": "JsonValue",
}

DATABASE_TYPE_MAP = {
    **DESIGN_TYPE_MAP,
    "foreign_key": "string",
}


@dataclass(slots=True)
class TypeLoweringResult:
    manifest: dict[str, Any]
    sources: dict[str, str] = field(default_factory=dict)
    errors: list[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.errors


class TypeLowerer:
    """Render the complete canonical TypeScript type world from frozen registries."""

    def lower(
        self,
        symbol_registry: dict[str, Any],
        file_registry: dict[str, Any],
    ) -> TypeLoweringResult:
        errors: list[str] = []
        symbols = _index_symbols(symbol_registry, errors, "ARC3301")
        locations = _index_symbol_locations(file_registry, errors, "ARC3302")
        _validate_registry_statuses(symbol_registry, file_registry, errors, "ARC3303")
        _validate_required_files(
            file_registry,
            {
                "shared/src/contracts/runtime.ts",
                "shared/src/contracts/index.ts",
                "shared/src/index.ts",
            },
            errors,
            "ARC3302",
        )
        definitions: list[dict[str, Any]] = []
        sources: dict[str, str] = {}

        if not errors:
            contract_files: dict[str, list[dict[str, Any]]] = {}
            entity_files: dict[str, list[dict[str, Any]]] = {}
            for symbol_id, symbol in sorted(symbols.items()):
                location = locations.get(symbol_id)
                if location is None:
                    errors.append(f"ARC3304 TYPE_LOCATION_MISSING: no file for {symbol_id}.")
                    continue
                path = str(location["path"])
                kind = str(symbol.get("kind", ""))
                if kind == "DATA_CONTRACT":
                    if not path.startswith("shared/src/contracts/"):
                        errors.append(
                            f"ARC3304 TYPE_LOCATION_MISSING: contract {symbol_id} is outside shared contracts."
                        )
                        continue
                    contract_files.setdefault(path, []).append(symbol)
                elif kind == "ENTITY_TYPE":
                    if path != "backend/src/db/schema.ts":
                        errors.append(
                            f"ARC3304 TYPE_LOCATION_MISSING: entity {symbol_id} is outside database schema."
                        )
                        continue
                    entity_files.setdefault(path, []).append(symbol)

            for path, rows in sorted(contract_files.items()):
                sources[path] = _render_contract_file(rows, errors)
                definitions.extend(_definition_rows(rows, path, "DATA_CONTRACT"))
            # Database lowering owns table bindings and inferred record types.
            for path, rows in sorted(entity_files.items()):
                definitions.extend(_definition_rows(rows, path, "ENTITY_TYPE"))

            runtime_path = "shared/src/contracts/runtime.ts"
            sources[runtime_path] = _render_runtime_types()
            contract_paths = sorted(contract_files)
            sources["shared/src/contracts/index.ts"] = _render_barrel(
                "shared/src/contracts/index.ts",
                [runtime_path, *contract_paths],
            )
            sources["shared/src/index.ts"] = (
                "// Generated by ARC. Do not edit.\n"
                'export * from "./contracts/index.js";\n'
            )
            definitions.extend(
                {
                    "symbol_id": f"SYSTEM.{symbol}",
                    "symbol": symbol,
                    "kind": "RUNTIME_TYPE",
                    "path": runtime_path,
                }
                for symbol in ("ApiErrorBody", "ApiErrorDetail", "JsonValue")
            )

        manifest = {
            "schema_version": TYPE_MANIFEST_SCHEMA_VERSION,
            "status": TYPES_GENERATED if not errors else "TYPE_LOWERING_FAILED",
            "definitions": sorted(definitions, key=lambda item: item["symbol_id"]),
            "generated_files": [] if errors else sorted(sources),
        }
        return TypeLoweringResult(
            manifest=manifest,
            sources={} if errors else sources,
            errors=list(dict.fromkeys(errors)),
        )


def _index_symbols(
    registry: Any,
    errors: list[str],
    code: str,
) -> dict[str, dict[str, Any]]:
    rows = registry.get("symbols", []) if isinstance(registry, dict) else []
    if not isinstance(rows, list):
        errors.append(f"{code} SYMBOL_REGISTRY_INVALID: symbols must be a list.")
        return {}
    result: dict[str, dict[str, Any]] = {}
    for row in rows:
        symbol_id = str(row.get("id", "")).strip() if isinstance(row, dict) else ""
        if not symbol_id or symbol_id in result:
            errors.append(f"{code} SYMBOL_REGISTRY_INVALID: invalid or duplicate symbol {symbol_id!r}.")
            continue
        result[symbol_id] = row
    return result


def _index_symbol_locations(
    registry: Any,
    errors: list[str],
    code: str,
) -> dict[str, dict[str, Any]]:
    rows = registry.get("symbol_locations", []) if isinstance(registry, dict) else []
    if not isinstance(rows, list):
        errors.append(f"{code} FILE_REGISTRY_INVALID: symbol_locations must be a list.")
        return {}
    result: dict[str, dict[str, Any]] = {}
    for row in rows:
        symbol_id = str(row.get("symbol_id", "")).strip() if isinstance(row, dict) else ""
        path = str(row.get("path", "")).strip() if isinstance(row, dict) else ""
        if not symbol_id or not path or symbol_id in result:
            errors.append(f"{code} FILE_REGISTRY_INVALID: invalid location for {symbol_id!r}.")
            continue
        result[symbol_id] = row
    return result


def _validate_registry_statuses(
    symbol_registry: Any,
    file_registry: Any,
    errors: list[str],
    code: str,
) -> None:
    if not isinstance(symbol_registry, dict) or symbol_registry.get("status") != "SYMBOLS_PLANNED":
        errors.append(f"{code} SYMBOL_REGISTRY_INVALID: symbols are not planned.")
    if not isinstance(file_registry, dict) or file_registry.get("status") != "FILES_PLANNED":
        errors.append(f"{code} FILE_REGISTRY_INVALID: files are not planned.")


def _validate_required_files(
    registry: Any,
    required: set[str],
    errors: list[str],
    code: str,
) -> None:
    rows = registry.get("files", []) if isinstance(registry, dict) else []
    if not isinstance(rows, list):
        errors.append(f"{code} FILE_REGISTRY_INVALID: files must be a list.")
        return
    paths = {
        str(row.get("path", ""))
        for row in rows
        if isinstance(row, dict) and row.get("path")
    }
    if required - paths:
        errors.append(
            f"{code} FILE_REGISTRY_INVALID: required files are missing: {sorted(required - paths)}."
        )


def _definition_rows(
    symbols: list[dict[str, Any]],
    path: str,
    kind: str,
) -> list[dict[str, Any]]:
    return [
        {
            "symbol_id": str(symbol["id"]),
            "symbol": str(symbol["symbol"]),
            "kind": kind,
            "path": path,
        }
        for symbol in symbols
    ]


def _render_runtime_types() -> str:
    return (
        "// Generated by ARC. Do not edit.\n"
        "export type JsonPrimitive = string | number | boolean | null;\n"
        "export type JsonValue = JsonPrimitive | JsonValue[] | { [key: string]: JsonValue };\n"
        "\n"
        "/** Single failure envelope shared by every API route and API client. */\n"
        "export interface ApiErrorDetail {\n"
        "  code: string;\n"
        "  message: string;\n"
        "  details?: JsonValue;\n"
        "}\n"
        "\n"
        "export interface ApiErrorBody {\n"
        "  error: ApiErrorDetail;\n"
        "}\n"
    )


def _render_contract_file(symbols: list[dict[str, Any]], errors: list[str]) -> str:
    uses_json = any(
        str(field_item.get("type", "")) == "json"
        for symbol in symbols
        for field_item in symbol.get("fields", [])
        if isinstance(field_item, dict)
    )
    lines = ["// Generated by ARC. Do not edit."]
    if uses_json:
        lines.extend(['import type { JsonValue } from "./runtime.js";', ""])
    for symbol in sorted(symbols, key=lambda item: str(item.get("id", ""))):
        name = str(symbol.get("symbol", ""))
        fields = symbol.get("fields", [])
        if not name or not isinstance(fields, list):
            errors.append(f"ARC3306 DATA_CONTRACT_INVALID: malformed contract {symbol.get('id')}.")
            continue
        lines.append(f"export interface {name} {{")
        for field_item in _coalesce_render_fields(fields, symbol, errors):
            if not isinstance(field_item, dict):
                errors.append(
                    f"ARC3306 DATA_CONTRACT_INVALID: malformed field in {symbol.get('id')}."
                )
                continue
            field_name = str(field_item.get("name", ""))
            type_name = _typescript_type(field_item.get("type"), DESIGN_TYPE_MAP, errors, "ARC3307")
            optional = "" if bool(field_item.get("required", True)) else "?"
            if not _is_typescript_property(field_name):
                errors.append(
                    f"ARC3306 DATA_CONTRACT_INVALID: invalid field name {field_name!r} in {symbol.get('id')}."
                )
                continue
            lines.append(f"  {field_name}{optional}: {type_name};")
        lines.extend(["}", ""])
    return "\n".join(lines).rstrip() + "\n"


def _coalesce_render_fields(
    fields: list[Any],
    symbol: dict[str, Any],
    errors: list[str],
) -> list[Any]:
    """Defensively keep stale registries from emitting duplicate properties."""

    by_name: dict[str, dict[str, Any]] = {}
    result: list[Any] = []
    for field_item in fields:
        if not isinstance(field_item, dict):
            result.append(field_item)
            continue
        name = str(field_item.get("name", "")).strip()
        existing = by_name.get(name)
        if existing is None:
            by_name[name] = field_item
            result.append(field_item)
            continue
        if existing.get("type") != field_item.get("type"):
            errors.append(
                f"ARC3306 DATA_CONTRACT_INVALID: property {name!r} has incompatible "
                f"types in {symbol.get('id')}."
            )
            continue
        existing["required"] = bool(existing.get("required")) or bool(
            field_item.get("required")
        )
    return result


def _render_entity_type_file(symbol: dict[str, Any], errors: list[str]) -> str:
    uses_json = any(
        isinstance(field_item, dict) and field_item.get("type") == "json"
        for field_item in symbol.get("fields", [])
    )
    lines = ["// Generated by ARC. Do not edit."]
    if uses_json:
        lines.extend(['import type { JsonValue } from "@arc/shared";', ""])
    lines.extend(_render_entity_interface(symbol, errors))
    return "\n".join(lines).rstrip() + "\n"


def _render_entity_interface(symbol: dict[str, Any], errors: list[str]) -> list[str]:
    name = str(symbol.get("symbol", ""))
    fields = symbol.get("fields", [])
    if not name or not isinstance(fields, list):
        errors.append(f"ARC3308 ENTITY_TYPE_INVALID: malformed entity {symbol.get('id')}.")
        return []
    lines = [f"export interface {name} {{"]
    for field_item in fields:
        if not isinstance(field_item, dict):
            errors.append(f"ARC3308 ENTITY_TYPE_INVALID: malformed field in {symbol.get('id')}.")
            continue
        field_name = str(field_item.get("name", ""))
        if not _is_typescript_property(field_name):
            errors.append(
                f"ARC3308 ENTITY_TYPE_INVALID: invalid field name {field_name!r} in {symbol.get('id')}."
            )
            continue
        type_name = _database_field_typescript_type(field_item, errors)
        nullable = " | null" if bool(field_item.get("nullable")) else ""
        lines.append(f"  {field_name}: {type_name}{nullable};")
    lines.extend(["}", ""])
    return lines


def _database_field_typescript_type(field_item: dict[str, Any], errors: list[str]) -> str:
    enum_values = field_item.get("properties", {}).get("enum")
    if isinstance(enum_values, list) and enum_values:
        return " | ".join(json.dumps(str(value), ensure_ascii=False) for value in enum_values)
    return _typescript_type(field_item.get("type"), DATABASE_TYPE_MAP, errors, "ARC3309")


def _typescript_type(
    value: Any,
    mapping: dict[str, str],
    errors: list[str],
    code: str,
) -> str:
    key = str(value)
    result = mapping.get(key)
    if result is None:
        errors.append(f"{code} TYPE_UNSUPPORTED: cannot lower type {key!r}.")
        return "never"
    return result


def _render_barrel(barrel_path: str, source_paths: list[str]) -> str:
    lines = ["// Generated by ARC. Do not edit."]
    for source_path in sorted(set(source_paths)):
        if source_path == barrel_path:
            continue
        specifier = posixpath.relpath(source_path, posixpath.dirname(barrel_path))
        if not specifier.startswith("."):
            specifier = f"./{specifier}"
        specifier = re.sub(r"\.ts$", ".js", specifier)
        lines.append(f'export * from "{specifier}";')
    return "\n".join(lines) + "\n"


def _is_typescript_property(value: str) -> bool:
    return re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", value) is not None
