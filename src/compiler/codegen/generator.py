from __future__ import annotations

from dataclasses import dataclass, field

from ..ir.implementation.project import ImplementationIR


@dataclass(slots=True)
class CodegenResult:
    sources: dict[str, str] = field(default_factory=dict)
    diagnostics: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, object]:
        return {"sources": dict(self.sources), "diagnostics": list(self.diagnostics)}


class DeterministicCodegen:
    """Generate stable source skeletons from Implementation IR only."""

    def generate(self, implementation: ImplementationIR) -> CodegenResult:
        result = CodegenResult()
        for file_id, file_ir in sorted(implementation.files.items()):
            symbols = [
                implementation.symbols[reference.target_id]
                for reference in file_ir.symbols
                if reference.target_id in implementation.symbols
            ]
            symbols.sort(key=lambda item: item.id)
            if file_ir.language == "python":
                lines = ["\"\"Generated by ARC deterministic codegen.\"\"\"", ""]
                for symbol in symbols:
                    lines.extend([f"def {self._safe(symbol.name)}(*args, **kwargs):", "    pass", ""])
            else:
                lines = ["// Generated by ARC deterministic codegen.", ""]
                for symbol in symbols:
                    lines.extend([f"export function {self._safe(symbol.name)}(...args: unknown[]): unknown {{", "  return undefined;", "}", ""])
            result.sources[file_ir.path] = "\n".join(lines).rstrip() + "\n"
        return result

    @staticmethod
    def _safe(value: str) -> str:
        import re
        name = re.sub(r"[^A-Za-z0-9_$]+", "_", value or "generated")
        if name[:1].isdigit():
            name = f"generated_{name}"
        return name or "generated"


__all__ = ["CodegenResult", "DeterministicCodegen"]
